"""Download every bus / tram / trolleybus stop and line in Debrecen from OpenStreetMap.

    python tools/fetch_osm_stops.py

Writes data/transit_stops.json (overwrites the small tram-only fallback).
Data © OpenStreetMap contributors, ODbL.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from flatwatch.transit import STOPS_FILE, parse_overpass  # noqa: E402

QUERY = """
[out:json][timeout:120];
area["name"="Debrecen"]["boundary"="administrative"]["admin_level"="8"]->.city;
rel(area.city)["type"="route"]["route"~"^(bus|tram|trolleybus)$"]->.routes;
.routes out body;
node(r.routes);
out body qt;
"""
ENDPOINTS = [
    "https://overpass-api.de/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
]


def main() -> None:
    data = None
    for url in ENDPOINTS:
        try:
            print(f"Querying {url} ...")
            r = requests.post(url, data={"data": QUERY}, timeout=180,
                              headers={"User-Agent": "flat-watch-debrecen-hackathon/1.0"})
            r.raise_for_status()
            data = r.json()
            break
        except Exception as exc:  # noqa: BLE001
            print(f"  failed: {exc}")
    if data is None:
        sys.exit("Could not reach Overpass. The fallback file is unchanged.")

    stops = parse_overpass(data)
    if len(stops) < 20:
        sys.exit(f"Only {len(stops)} stops found - something is off, keeping the fallback file.")
    lines = sorted({l for s in stops for l in s["lines"]})
    STOPS_FILE.write_text(json.dumps({
        "_source": "openstreetmap",
        "_note": "Data © OpenStreetMap contributors (ODbL). Generated by tools/fetch_osm_stops.py",
        "stops": stops,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Saved {len(stops)} stops and {len(lines)} lines to {STOPS_FILE}")
    print("Lines:", ", ".join(lines))


if __name__ == "__main__":
    main()
